def kit_source() -> str:
    return "\n".join(p.read_text(encoding="utf-8") for p in sorted(KIT.glob("*.js")) if p.name != SCULPT_JS.name)


def check() -> List[str]:
    errs: List[str] = []
    man = load(MANIFEST)
    errs += [f"manifest: {e}" for e in schema_errors(ASSET_SPEC, man) if "jsonschema not installed" not in e]
    ids = [a["id"] for a in man["assets"]]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        errs.append(f"manifest: duplicate ids {sorted(dup)}")
    src = kit_source()
    for a in man["assets"]:
        for f in a.get("files", []):
            if not (ROOT / f["path"]).exists():
                errs.append(f"{a['id']}: file missing: {f['path']}")
        pv = a.get("preview")
        if pv and not (ROOT / pv).exists():
            errs.append(f"{a['id']}: preview missing: {pv} (run fitness.py sheets)")
        api = a.get("api", "")
        m = re.match(r"Studio\.kit\.fitness\.([A-Za-z.]+)", api)
        if m:
            parts = m.group(1).split(".")
            leaf = parts[-1]
            if not re.search(r"\b" + re.escape(leaf) + r"\s*[=:]", src) and f"'{leaf}'" not in src and f"EX.{leaf}" not in src:
                errs.append(f"{a['id']}: api {api} not found in the kit source")
        lic = a.get("license", {})
        if lic.get("commercial_use") is not True and a.get("status") != "excluded":
            errs.append(f"{a['id']}: not cleared for commercial use but not marked excluded")
    mdata = load(DATA / "muscles.json")
    errs += sculpt_muscle_errors({m["id"] for m in mdata["muscles"]})
    # exercises may also name muscles Tibi does not draw (deep or unmodelled: listed in deep_not_drawn)
    muscles = {m["id"] for m in mdata["muscles"]} | {m["id"] for m in mdata.get("deep_not_drawn", [])}
    exs = load(DATA / "exercises.json")["exercises"]
    js_ex = set(re.findall(r"EX\['([a-z-]+)'\]", src)) | set(re.findall(r"EX\.([a-z]+) = ", src)) | {"walk", "jog", "sprint"}
    for e in exs:
        if e["id"] not in js_ex and e.get("engine") != "3d":
            errs.append(f"exercises.json '{e['id']}' has no kinematics in exercises.js")
        for mid in e["muscles"]["primary"] + e["muscles"]["secondary"] + e["muscles"].get("stabilizer", []):
            if mid not in muscles:
                errs.append(f"exercise {e['id']}: unknown muscle id '{mid}'")
        for ph in e["phases"] + e["errors"]:
            if ph.get("pose") and f"'{ph['pose']}'" not in src:
                errs.append(f"exercise {e['id']}: pose '{ph['pose']}' not in exercises.js")
        if e.get("rig3d") or e.get("engine") == "3d" or e.get("classification"):
            errs += [f"exercise {e['id']}: {m}" for m in schema_errors(EXERCISE_SPEC, e)]
    errs += rig3d_role_errors(exs)
    for e in sorted(js_ex - {x["id"] for x in exs}):
        errs.append(f"exercises.js has '{e}' but exercises.json does not")
    if LIBRARY_JS.exists() and LIBRARY_JS.read_text(encoding="utf-8") != library_js():
        errs.append("src/studio/kits/fitness/library.js is stale (fitness.py library)")
    if sculpt_stale():
        errs.append("src/studio/kits/fitness/sculpt-data.js is stale (fitness.py sculpt)")
    routed = {a for r in spec()["routing"] for a in r["assets"]}
    for a in sorted(routed - set(ids)):
        errs.append(f"specs/fitness-spec.json routing names unknown asset '{a}'")
    return errs


def sculpt_muscle_errors(muscles: set) -> List[str]:
    """muscles.json ids <-> the Cobalt Sculpt Tibi: each id maps (sculpt.js ALIAS) to muscle planes Tibi draws."""
    errs: List[str] = []
    js = (KIT / "sculpt.js").read_text(encoding="utf-8")
    m = re.search(r"var ALIAS = \{(.*?)\};", js, re.S)
    alias = dict(re.findall(r"'([a-z-]+)': \[([^\]]*)\]", m.group(1))) if m else {}
    alias = {k: re.findall(r"'([a-z@]+)'", v) for k, v in alias.items()}
    data = sculpt_exporter().payload()
    planes = {nm for seg in data["segments"].values() for nm, _ in seg["mus"]}
    for mid in sorted(muscles):
        keys = alias.get(mid)
        if not keys:
            errs.append(f"muscles.json lists '{mid}' but sculpt.js ALIAS has no mapping to Tibi's muscle planes")
            continue
        for k in keys:
            if k not in planes:
                errs.append(f"sculpt.js ALIAS maps '{mid}' to '{k}', which Tibi never draws")
    return errs


