# --------------------------------------------------------------------------- dossier
def dossier_errors(d: Dict[str, Any]) -> List[str]:
    errs = [e for e in schema_errors(DOSSIER_SPEC, d)]
    if not isinstance(d, dict):
        return errs
    src_ids = {s.get("id") for s in d.get("sources", [])}
    used = set()
    for c in d.get("claims", []):
        for s in c.get("sources", []):
            used.add(s)
            if s not in src_ids:
                errs.append(f"claim {c.get('id')}: cites unknown source '{s}'")
        if c.get("grade") in ("strong",) and not any(
                (next((x for x in d["sources"] if x["id"] == s), {}).get("design", "")).startswith(("systematic", "meta")) for s in c.get("sources", [])):
            errs.append(f"claim {c.get('id')}: graded 'strong' without a systematic review or meta-analysis among its sources")
    for s in d.get("sources", []):
        if s.get("id") not in used:
            errs.append(f"source {s.get('id')}: listed but no claim cites it")
        if str(s.get("verified_via", "")).strip().lower() in ("", "memory", "todo"):
            errs.append(f"source {s.get('id')}: verified_via must say how the citation was checked")
        if "TODO" in json.dumps(s):
            errs.append(f"source {s.get('id')}: still has TODO fields")
    if "TODO" in json.dumps(d.get("claims", [])):
        errs.append("claims still have TODO fields")
    return errs


