def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def spec() -> Dict[str, Any]:
    return load(SPEC)


def validator(schema_path: Path):
    try:
        import jsonschema  # noqa: F401
    except ImportError:
        return None
    import jsonschema
    return jsonschema.Draft7Validator(load(schema_path))


def schema_errors(schema_path: Path, data: Any) -> List[str]:
    v = validator(schema_path)
    if v is None:
        return [f"jsonschema not installed in this interpreter; run with python3.12 or .venv/bin/python to validate against {schema_path.name}"]
    return [f"{'/'.join(str(p) for p in e.path) or '(root)'}: {e.message}" for e in v.iter_errors(data)]


