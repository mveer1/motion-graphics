# --------------------------------------------------------------------------- review
def review_result(r: Dict[str, Any]) -> Dict[str, Any]:
    rub = spec()["rubric"]
    errs = list(schema_errors(REVIEW_SPEC, r))
    scores = {k: v["score"] for k, v in r.get("scores", {}).items()}
    crit = [d["id"] for d in rub["dimensions"] if d["critical"]]
    fails = []
    if scores:
        mean = sum(scores.values()) / len(scores)
        for k, v in scores.items():
            if v < rub["pass"]["min_each"]:
                fails.append(f"{k} {v} < {rub['pass']['min_each']}")
        for k in crit:
            if scores.get(k, 0) < rub["pass"]["critical_min"]:
                fails.append(f"critical dimension {k} {scores.get(k)} < {rub['pass']['critical_min']}")
        if mean < rub["pass"]["min_mean"]:
            fails.append(f"mean {mean:.2f} < {rub['pass']['min_mean']}")
    else:
        mean = 0.0
        fails.append("no scores")
    open_crit = [i["id"] for i in r.get("issues", []) if i.get("severity") == "critical" and i.get("status") == "open"]
    if open_crit:
        fails.append(f"open critical issues: {', '.join(open_crit)}")
    open_rerender = [i["id"] for i in r.get("issues", []) if i.get("status") == "open" and i.get("rerender")]
    passed = not errs and not fails
    return {"errors": errs, "fails": fails, "mean": mean, "passed": passed, "open_rerender": open_rerender}


def cmd_review(args: argparse.Namespace) -> int:
    path = PROJECTS / args.slug / "qa" / "fitness-review.json"
    if args.init:
        if path.exists():
            print(f"{path.relative_to(ROOT)} exists; not overwriting.")
            return 1
        rub = spec()["rubric"]
        write_json(path, {
            "slug": args.slug, "render": f"out/{args.slug}-<format>.mp4", "reviewed_at": date.today().isoformat(),
            "reviewer": "TODO", "method": [],
            "scores": {d["id"]: {"score": 1, "evidence": "TODO: " + d["question"]} for d in rub["dimensions"]},
            "issues": [], "verdict": "pending", "notes": rub["critical_rule"],
        })
        print(f"Wrote {path.relative_to(ROOT)}; score it after watching the render.")
        return 0
    if not path.exists():
        print(f"{path.relative_to(ROOT)} missing; run with --init after the render.")
        return 1
    r = load(path)
    res = review_result(r)
    for e in res["errors"]:
        print("ERROR " + e)
    for f in res["fails"]:
        print("FAIL  " + f)
    if res["open_rerender"]:
        print("OPEN  issues needing a re-render: " + ", ".join(res["open_rerender"]))
    claimed = r.get("verdict")
    computed = "pass" if res["passed"] else "fail"
    if claimed != computed:
        print(f"ERROR verdict says '{claimed}' but the rubric computes '{computed}'.")
        res["errors"].append("verdict mismatch")
    print(f"fitness review: mean {res['mean']:.2f}, {'PASS' if res['passed'] and not res['errors'] else 'FAIL'}.")
    return 0 if res["passed"] and not res["errors"] else 1


