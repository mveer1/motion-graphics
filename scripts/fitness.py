def words_in(text: str, kw: str) -> bool:
    return re.search(r"(?<![a-z])" + re.escape(kw.lower()) + r"(?![a-z])", text.lower()) is not None


def classify(topic: str, form: Optional[str] = None) -> Dict[str, Any]:
    sp = spec()
    scores = []
    for p in sp["pillars"]:
        hits = [k for k in p["keywords"] if words_in(topic, k)]
        scores.append((len(hits), p, hits))
    scores.sort(key=lambda s: -s[0])
    best = scores[0]
    pillar = best[1] if best[0] > 0 else next(p for p in sp["pillars"] if p["id"] == "performance")
    systems: List[str] = []
    assets: List[str] = []
    for r in sp["routing"]:
        if any(words_in(topic, w) for w in r["when"]):
            systems += [s for s in r["systems"] if s not in systems]
            assets += [a for a in r["assets"] if a not in assets]
    if not systems:
        systems = ["character-animation", "scientific-infographics"]
        assets = ["tibi-sculpt-male", "tibi-sculpt-female", "tibi-sculpt-activation", "chart-time-series"]
    for a in ["brand-title-card", "brand-lower-third", "brand-evidence-badge", "brand-citation", "brand-logo"]:
        if a not in assets:
            assets.append(a)
    chosen_form = form or pillar["default_form"]
    manifest = {a["id"]: a for a in load(MANIFEST)["assets"]} if MANIFEST.exists() else {}
    missing = [a for a in assets if manifest and a not in manifest]
    return {
        "topic": topic,
        "pillar": pillar["id"],
        "pillar_name": pillar["name"],
        "pillar_hits": best[2],
        "alternatives": [{"pillar": s[1]["id"], "hits": s[2]} for s in scores[1:] if s[0] > 0],
        "form": chosen_form,
        "form_structure": sp["forms"][chosen_form]["structure"],
        "form_rules": sp["forms"][chosen_form]["fitness_rules"],
        "categories": ["fitness"] + pillar.get("default_category_extra", []),
        "style_template": sp["brand"]["style_template"],
        "style_system": sp["brand"]["style_system"],
        "voice": sp["brand"]["voice"],
        "visual_systems": systems,
        "assets": assets,
        "unknown_assets": missing,
    }


def cmd_classify(args: argparse.Namespace) -> int:
    c = classify(args.topic, args.type)
    if args.json:
        print(json.dumps(c, indent=2))
        return 0
    print(f"Topic      : {c['topic']}")
    print(f"Pillar     : {c['pillar_name']} ({c['pillar']}); matched {', '.join(c['pillar_hits']) or 'nothing (default)'}")
    if c["alternatives"]:
        print("Also fits  : " + "; ".join(f"{a['pillar']} ({', '.join(a['hits'])})" for a in c["alternatives"]))
    print(f"Form       : {c['form']}  ({c['form_structure']})")
    print(f"Categories : {', '.join(c['categories'])}   style template {c['style_template']} on {c['style_system']}")
    print(f"Visual sys.: {', '.join(c['visual_systems'])}")
    print(f"Kit assets : {', '.join(c['assets'])}")
    if c["unknown_assets"]:
        print(f"WARNING: routing names assets missing from the manifest: {', '.join(c['unknown_assets'])}")
    return 0


