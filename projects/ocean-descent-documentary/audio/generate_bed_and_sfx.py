#!/usr/bin/env python3
"""Layered sound design for 'Where the Light Goes': one bed per depth zone, foley, and 76 bells that ring exactly
when the 76 dots ignite. Writes bed.wav, sfx-track.wav and ../src/cues.js (the visual timing, same numbers).
Original and deterministic (seeded); no samples, no third-party licences. Run: .venv/bin/python generate_bed_and_sfx.py
"""
import json, wave
from pathlib import Path
import numpy as np

HERE = Path(__file__).parent
SR = 44100
END = 49.5
rng = np.random.default_rng(7)

# ---- one set of cue times for sound AND picture (seconds)
CUES = {
  "s1": {"surfaceOut": 0.0, "spectrum": 4.6, "red": 5.9, "orange": 6.5, "yellow": 7.0, "green": 7.5, "blue": 8.1},
  "s2": {"push": 9.0, "shafts": 9.7, "jelly": 10.6, "zone": 14.5, "bracket": 15.3},
  "s3": {"fade": 19.4, "one": 20.3, "lines": 22.8, "roll": 27.7, "deep": 29.2},
  "s4": {"iris": 33.0, "label": 33.9, "grid": 38.2, "ignite": 40.8, "igniteSpan": 3.0, "number": 43.4},
  "s5": {"text": 45.2, "dim": 47.4},
  "end": END,
}
order = rng.permutation(100)[:76]
CUES["dots"] = [{"i": int(i), "t": round(CUES["s4"]["ignite"] + k * CUES["s4"]["igniteSpan"] / 76, 3)} for k, i in enumerate(order)]
(HERE / "cues.json").write_text(json.dumps(CUES, indent=1))
(HERE.parent / "src" / "cues.js").write_text("// generated by audio/generate_bed_and_sfx.py: the single source of cue timing for picture and sound\nwindow.CUES = " + json.dumps(CUES) + ";\n")

def t(d): return np.arange(int(d * SR)) / SR
def write(p, x):
    x = np.clip(x, -1, 1)
    with wave.open(str(p), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((x * 32767).astype(np.int16).tobytes())
def lp(x, fc):
    a = np.exp(-2 * np.pi * fc / SR); y = np.zeros_like(x); s = 0.0
    for i in range(len(x)): s = (1 - a) * x[i] + a * s; y[i] = s
    return y
def env(d, a, dec): k = t(d); return np.minimum(k / a, 1) * np.exp(-k / dec)
def place(buf, snd, at, g=1.0):
    i = int(at * SR); j = min(len(buf), i + len(snd))
    if 0 <= i < len(buf): buf[i:j] += g * snd[: j - i]
def curve(pts):  # piecewise-linear control curve over time
    xs, ys = zip(*pts); return np.interp(t(END), xs, ys)

N = int(END * SR); tt = t(END)
# ---- BED: noise-based water wash that darkens with depth + a low drone that grows
noise = rng.standard_normal(N)
wash = lp(noise, 2400) * 0.5
wash_dark = lp(noise, 380)
mix_depth = curve([(0, 0), (9, 0.3), (19, 1.0), (END, 1.0)])
wash = wash * (1 - mix_depth) + wash_dark * mix_depth
lvl = curve([(0, .55), (8.5, .5), (9.5, .42), (19, .3), (20, .38), (33, .35), (33.6, .12), (38, .1), (44, .12), (45.5, .06), (48, 0.02), (END, 0.0)])
bed = wash * lvl * 0.12
drone = np.sin(2 * np.pi * 55 * tt) * 0.5 + np.sin(2 * np.pi * 82.4 * tt) * 0.25 + np.sin(2 * np.pi * 41.2 * tt) * 0.35
dlvl = curve([(0, 0), (8, .0), (11, .25), (19, .35), (27, .5), (32.8, .95), (33.4, .25), (44, .25), (46, .1), (END, 0)])
bed += drone * dlvl * 0.05 * (0.85 + 0.15 * np.sin(2 * np.pi * 0.11 * tt))
# surface shimmer (high airy sine cluster) only in s1
for f in (880, 1320, 1760):
    bed += np.sin(2 * np.pi * f * tt + np.sin(tt * .7)) * curve([(0, 0.03), (6, 0.02), (9, 0)]) * 0.12

# ---- FOLEY
sfx = np.zeros(N)
def bubble(at, g=.35):
    d = 0.09; k = t(d); f = 700 + 2600 * (k / d)
    place(sfx, np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-k / 0.03), at, g * 0.3)
for at in np.sort(rng.uniform(0.6, 8.6, 22)): bubble(at, 0.5 * (1 - at / 10))
for at in np.sort(rng.uniform(9.5, 17, 9)): bubble(at, 0.18)
def thum(at, g=.5):  # soft low pulse (the jelly)
    d = .7; k = t(d); place(sfx, np.sin(2 * np.pi * 62 * k) * np.exp(-k / .18) * np.minimum(k / .06, 1), at, g * 0.5)
for at in np.arange(CUES["s2"]["jelly"] + .6, 19.2, 2.2): thum(at, .45)
def tick(at, g=.3, f=2600):
    k = t(.025); place(sfx, (rng.standard_normal(len(k)) * .4 + np.sin(2 * np.pi * f * k)) * env(.025, .0005, .006), at, g * .22)
tick(CUES["s3"]["one"], .4); 
for at in np.arange(CUES["s3"]["lines"], CUES["s3"]["lines"] + 4.2, .55): tick(at, .25, 1900)
for at in np.arange(CUES["s3"]["roll"], CUES["s3"]["roll"] + 4.7, .06): tick(at, .22, 1500 + (at - CUES["s3"]["roll"]) * 500)
def creak(at, d=1.2, g=.4):
    k = t(d); x = rng.standard_normal(len(k)); x = lp(x, 520) - lp(x, 160)
    place(sfx, x * np.sin(np.pi * k / d) ** 2 * (0.6 + 0.4 * np.sin(2 * np.pi * 7 * k)), at, g * 0.8)
for at in (CUES["s3"]["roll"] + .2, CUES["s3"]["roll"] + 1.7, CUES["s3"]["roll"] + 3.1): creak(at, 1.3, .45)
def thud(at, f=58, g=.8, d=.8):
    k = t(d); place(sfx, np.sin(2 * np.pi * f * (1 - .25 * k / d) * k) * np.exp(-k / .22) * np.minimum(k / .01, 1), at, g * .55)
thud(CUES["s3"]["deep"], 48, .9, 1.2); thud(CUES["s4"]["iris"], 40, .7, 1.6)
# 76 bells: pentatonic, one per ignited dot, quiet and spaced
pent = np.array([880, 988, 1175, 1319, 1568, 1760, 2093, 2349])
for k, d in enumerate(CUES["dots"]):
    f = pent[int(rng.integers(0, len(pent)))]; kk = t(1.4)
    snd = (np.sin(2 * np.pi * f * kk) + .3 * np.sin(2 * np.pi * 2.76 * f * kk) * np.exp(-kk * 6)) * env(1.4, .003, .45)
    place(sfx, snd, d["t"], .045 + .03 * rng.random())
thud(CUES["s4"]["number"], 44, .75, 1.4)
def bell(at, f, g=.2, d=2.4):
    k = t(d); place(sfx, (np.sin(2 * np.pi * f * k) + .2 * np.sin(2 * np.pi * 3 * f * k)) * env(d, .004, .9), at, g)
bell(CUES["s5"]["text"] + 1.6, 1319, .12, 2.6)
peak = np.max(np.abs(sfx)); sfx = sfx / (peak or 1) * .5
write(HERE / "bed.wav", bed / (np.max(np.abs(bed)) or 1) * .8); write(HERE / "sfx-track.wav", sfx)
print("bed.wav, sfx-track.wav, src/cues.js written;", len(CUES["dots"]), "dots ignite", CUES["dots"][0]["t"], "->", CUES["dots"][-1]["t"])
