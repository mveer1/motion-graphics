"""Tibi shared anatomy rig.
All geometry is authored in a neutral pose (head = 100 units tall, centre line x=0, y down),
as smooth Catmull-Rom -> cubic Bezier splines. Each segment is registered with its own pivot so
that local coordinates = neutral - pivot (the group origin IS the joint)."""
import math

def n(v):
    s = f"{v:.1f}"
    return s[:-2] if s.endswith('.0') else s

class Sp:
    """closed/open spline through points; (x,y,'c') marks a corner"""
    def __init__(s, pts, closed=True, t=1.0):
        s.pts = [(p[0], p[1], len(p) > 2 and p[2] == 'c') for p in pts]
        s.closed, s.t = closed, t
        s.segs = s._segs()
    def _segs(s):
        P = s.pts; N = len(P); out = []
        cnt = N if s.closed else N - 1
        g = (lambda i: P[i % N]) if s.closed else (lambda i: P[max(0, min(N - 1, i))])
        k = s.t / 6
        for i in range(cnt):
            p0, p1, p2, p3 = g(i - 1), g(i), g(i + 1), g(i + 2)
            c1 = (p1[0], p1[1]) if p1[2] else (p1[0] + (p2[0] - p0[0]) * k, p1[1] + (p2[1] - p0[1]) * k)
            c2 = (p2[0], p2[1]) if p2[2] else (p2[0] - (p3[0] - p1[0]) * k, p2[1] - (p3[1] - p1[1]) * k)
            out.append((p1, c1, c2, p2))
        return out
    def d(s):
        a = s.segs[0][0]
        r = f"M{n(a[0])},{n(a[1])}"
        for p1, c1, c2, p2 in s.segs:
            r += f"C{n(c1[0])},{n(c1[1])} {n(c2[0])},{n(c2[1])} {n(p2[0])},{n(p2[1])}"
        return r + ("Z" if s.closed else "")
    def d_edges(s, skip):
        """stroke path of all segments not in skip (open sub-paths, so joint ends stay unstroked)"""
        r = ""; prev = None
        for i, (p1, c1, c2, p2) in enumerate(s.segs):
            if i in skip:
                prev = None; continue
            if prev != i - 1:
                r += f"M{n(p1[0])},{n(p1[1])}"
            r += f"C{n(c1[0])},{n(c1[1])} {n(c2[0])},{n(c2[1])} {n(p2[0])},{n(p2[1])}"
            prev = i
        return r

def mx(pts):
    return [(-p[0], p[1]) + tuple(p[2:]) for p in pts]

def sym(left, ts=1, bs=1):
    """full closed outline from the viewer-left half (first & last point on the axis)"""
    L = len(left)
    full = list(left) + mx(left[-2:0:-1])
    N = len(full)
    skip = set(range(0, ts)) | set(range(N - ts, N)) | set(range(L - 1 - bs, L - 1)) | set(range(L - 1, L - 1 + bs))
    return full, skip

def blob(cx, cy, rx, ry, rot=0, p=2.6, k=12):
    out = []
    r = math.radians(rot)
    for i in range(k):
        a = 2 * math.pi * i / k
        c, s_ = math.cos(a), math.sin(a)
        x = rx * math.copysign(abs(c) ** (2 / p), c)
        y = ry * math.copysign(abs(s_) ** (2 / p), s_)
        out.append((cx + x * math.cos(r) - y * math.sin(r), cy + x * math.sin(r) + y * math.cos(r)))
    return out

def capsule(x0, y0, x1, y1, w0, w1=None):
    w1 = w0 if w1 is None else w1
    dx, dy = x1 - x0, y1 - y0
    L = math.hypot(dx, dy); dx, dy = dx / L, dy / L
    nx, ny = -dy, dx
    r0, r1 = w0 / 2, w1 / 2
    rm = (r0 + r1) / 2 * 0.9
    mx_, my_ = (x0 + x1) / 2, (y0 + y1) / 2
    return [(x0 - dx * r0 * .95, y0 - dy * r0 * .95), (x0 + nx * r0, y0 + ny * r0), (mx_ + nx * rm, my_ + ny * rm),
            (x1 + nx * r1, y1 + ny * r1), (x1 + dx * r1 * .95, y1 + dy * r1 * .95), (x1 - nx * r1, y1 - ny * r1),
            (mx_ - nx * rm, my_ - ny * rm), (x0 - nx * r0, y0 - ny * r0)]

def R(th, v):
    c, s_ = math.cos(math.radians(th)), math.sin(math.radians(th))
    return (v[0] * c - v[1] * s_, v[0] * s_ + v[1] * c)

